import { expect, test } from '@playwright/test'

test('HTTPS: формы email-регистрации и восстановления доступны без отправки настоящих писем', async ({ page }) => {
  const errors: string[] = [], submissions: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('request', request => { if (request.method() === 'POST') submissions.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click()
  await expect(page.getByLabel('Почта', { exact: true })).toBeFocused()
  await expect(page.getByLabel('Часовой пояс дневника')).toBeVisible()
  await page.getByRole('button', { name: 'Отправить ссылку', exact: true }).click()
  await expect(page.getByLabel('Почта', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Уже есть аккаунт? Войти', exact: true }).click()
  await page.getByRole('button', { name: 'Забыли пароль?', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Восстановление доступа', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Отправить ссылку', exact: true }).click()
  await expect(page.getByLabel('Почта', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.goto('/#auth=reset_password&token=' + 'f'.repeat(64))
  await expect(page.getByRole('heading', { name: 'Задайте новый пароль', exact: true })).toBeVisible()
  await expect(page).not.toHaveURL(/token=/)
  await page.getByRole('button', { name: 'Сохранить пароль', exact: true }).click()
  await expect(page.getByLabel('Новый пароль', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  expect(submissions).toEqual([])
  expect(errors).toEqual([])
  expect((await page.request.get('/api/v1/test-mail')).status()).toBe(404)
  expect((await page.request.get('/api/v1/test-auth-window')).status()).toBe(404)
  expect((await page.request.get('/api/v1/auth/email')).status()).toBe(401)
})
