import { expect, test } from './fixtures'

test.use({ timezoneId: 'Europe/Moscow' })

test('питание сохраняет независимые снимки и копии при правке каталога, удалении и перезагрузке', async ({ page, baseURL }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => {
    const url = new URL(request.url())
    if ((url.protocol === 'http:' || url.protocol === 'https:') && url.origin !== baseURL) external.push(url.href)
  })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#profile')
  await page.getByLabel('Имя (необязательно)').fill('Синтетический сценарий питания')
  await page.getByLabel('Рост, см').fill('170')
  await page.getByLabel('Вес, кг').fill('70')
  await page.getByLabel('Дата первого измерения').fill('2026-10-12')
  await page.getByRole('button', { name: 'Создать профиль' }).click()
  await expect(page.getByText('Профиль и первое измерение сохранены', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Разделы дневника' }).getByRole('link', { name: 'Питание', exact: true }).click()

  const originalName = 'Синтетический продукт для дневника'
  const changedName = 'Изменённый синтетический продукт'
  const newProduct = page.getByRole('form', { name: 'Новый продукт', exact: true })
  await newProduct.getByLabel('Название продукта').fill(originalName)
  await newProduct.getByLabel('Калории на 100 г, ккал').fill('200')
  await newProduct.getByLabel('Белки на 100 г, г (необязательно)').fill('0')
  await newProduct.getByLabel('Углеводы на 100 г, г (необязательно)').fill('30')
  await newProduct.getByLabel('Источник (необязательно)').fill('Синтетическая этикетка')
  await newProduct.getByRole('button', { name: 'Сохранить продукт' }).click()
  const catalog = page.getByRole('list', { name: 'Каталог продуктов', exact: true })
  await expect(catalog.getByText(originalName, { exact: true })).toBeVisible()
  const food = page.getByRole('form', { name: 'Добавление еды', exact: true })
  await food.getByLabel('Продукт для записи').selectOption({ label: originalName })
  await food.getByLabel('Приём пищи', { exact: true }).selectOption('lunch')
  await food.getByLabel('Масса порции, г').fill('150')
  await food.getByLabel('Комментарий к еде (необязательно)').fill('Синтетическая запись обеда')
  await food.getByRole('button', { name: 'Добавить еду' }).click()
  const journal = page.getByRole('list', { name: 'Еда выбранного дня' })
  await expect(journal.getByRole('listitem')).toHaveCount(1)
  await expect(journal.getByText('Обед · 150 г · 300 ккал', { exact: true })).toBeVisible()
  await journal.getByRole('button', { name: `Изменить запись еды 1: ${originalName}`, exact: true }).click()
  const editFood = page.getByRole('form', { name: 'Редактирование еды', exact: true })
  await editFood.getByLabel('Масса порции, г').fill('125')
  await editFood.getByRole('button', { name: 'Сохранить запись еды' }).click()
  await expect(journal.getByText('Обед · 125 г · 250 ккал', { exact: true })).toBeVisible()
  const summary = page.getByRole('region', { name: 'Итоги питания' })
  await expect(summary.getByText('Калории: 250 ккал', { exact: true })).toBeVisible()
  await expect(summary.getByText('Белки: 0 г', { exact: true })).toBeVisible()
  await expect(summary.getByText('Жиры: нет данных', { exact: true })).toBeVisible()
  await expect(summary.getByText('Углеводы: 37,5 г', { exact: true })).toBeVisible()

  await catalog.getByRole('button', { name: `Править продукт ${originalName}`, exact: true }).click()
  const editProduct = page.getByRole('form', { name: 'Редактирование продукта', exact: true })
  await editProduct.getByLabel('Название продукта').fill(changedName)
  await editProduct.getByLabel('Калории на 100 г, ккал').fill('900')
  await editProduct.getByLabel('Белки на 100 г, г (необязательно)').fill('90')
  await editProduct.getByLabel('Жиры на 100 г, г (необязательно)').fill('10')
  await editProduct.getByLabel('Углеводы на 100 г, г (необязательно)').fill('1')
  await editProduct.getByLabel('Источник (необязательно)').fill('Новая синтетическая этикетка')
  await editProduct.getByRole('button', { name: 'Сохранить продукт' }).click()
  await expect(catalog.getByText(changedName, { exact: true })).toBeVisible()
  await catalog.getByRole('button', { name: `Архивировать продукт ${changedName}`, exact: true }).click()
  await page.getByRole('checkbox', { name: 'Показать архив' }).check()
  await expect(catalog.getByText('· В архиве', { exact: true })).toBeVisible()
  await expect(journal.getByText(originalName, { exact: true })).toBeVisible()
  await expect(journal.getByText('Источник: Синтетическая этикетка', { exact: true })).toBeVisible()
  await expect(journal.getByText('Обед · 125 г · 250 ккал', { exact: true })).toBeVisible()
  await journal.getByRole('button', { name: `Изменить запись еды 1: ${originalName}`, exact: true }).click()
  await editFood.getByLabel('Масса порции, г').fill('777')
  await editFood.getByRole('button', { name: 'Отменить правку еды' }).click()
  await expect(journal.getByText('Обед · 125 г · 250 ккал', { exact: true })).toBeVisible()

  const copy = page.getByRole('form', { name: 'Копирование приёма пищи' })
  await copy.getByLabel('Приём для копирования').selectOption('lunch')
  await copy.getByLabel('Дата копии').fill('2026-10-13')
  await copy.getByRole('button', { name: 'Копировать приём', exact: true }).click()
  await expect(page.getByText('Приём пищи скопирован за 13.10.2026', { exact: true })).toBeVisible()
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(journal.getByRole('listitem')).toHaveCount(1)
  await expect(journal.getByText(originalName, { exact: true })).toBeVisible()
  await expect(journal.getByText('Синтетическая запись обеда', { exact: true })).toBeVisible()
  await expect(summary.getByRole('checkbox', { name: 'За этот день внесена вся еда' })).not.toBeChecked()
  await summary.getByRole('checkbox', { name: 'За этот день внесена вся еда' }).click()
  await expect(summary.getByRole('checkbox', { name: 'За этот день внесена вся еда' })).toBeChecked()
  await expect(summary.getByText('Вся еда за день внесена.', { exact: true })).toBeVisible()

  await page.getByLabel('День дневника').fill('2026-10-14')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  const remove = journal.getByRole('button', { name: `Удалить запись еды 1: ${originalName}`, exact: true })
  await remove.click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(journal.getByRole('listitem')).toHaveCount(1)
  await remove.click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect(page.getByText('За этот день нет записей еды.', { exact: true })).toBeVisible()
  await expect(summary.getByText('Калории: нет данных', { exact: true })).toBeVisible()

  // Deleting the source must leave the copied entry intact, proving independent IDs.
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(journal.getByRole('listitem')).toHaveCount(1)
  await expect(journal.getByText('Обед · 125 г · 250 ккал', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Разделы дневника' }).getByRole('link', { name: 'Сегодня', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Сегодня', level: 1 })).toBeVisible()
  await expect(summary.getByText('Калории: 250 ккал', { exact: true })).toBeVisible()
  await expect(summary.getByText('Белки: 0 г', { exact: true })).toBeVisible()
  await expect(summary.getByText('Жиры: нет данных', { exact: true })).toBeVisible()
  await expect(summary.getByRole('checkbox', { name: 'За этот день внесена вся еда' })).toBeChecked()
  await page.reload()
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(summary.getByText('Калории: 250 ккал', { exact: true })).toBeVisible()
  await expect(summary.getByText('Жиры: нет данных', { exact: true })).toBeVisible()
  await expect(summary.getByRole('checkbox', { name: 'За этот день внесена вся еда' })).toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
