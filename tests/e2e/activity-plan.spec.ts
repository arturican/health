import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Europe/Moscow' })

test('общий расход не складывается с активностью, версии плана и правки тренировок сохраняются после reload', async ({ page, baseURL }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { if (new URL(request.url()).origin !== baseURL) external.push(request.url()) })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#profile')
  await page.getByLabel('Имя (необязательно)', { exact: true }).fill('Синтетический профиль активности')
  await page.getByLabel('Рост, см', { exact: true }).fill('170')
  await page.getByLabel('Дата рождения (необязательно)', { exact: true }).fill('1996-10-14')
  await page.getByLabel('Пол для формулы расхода (необязательно)', { exact: true }).selectOption('male')
  await page.getByLabel('Вес, кг', { exact: true }).fill('70')
  await page.getByLabel('Дата первого измерения', { exact: true }).fill('2026-10-12')
  await page.getByRole('button', { name: 'Создать профиль', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Профиль и первое измерение сохранены' })).toBeVisible()
  const navigation = page.getByRole('navigation', { name: 'Разделы дневника', exact: true })
  await navigation.getByRole('link', { name: 'Настройки', exact: true }).click()
  const plan = page.getByRole('form', { name: 'Новая версия энергетического плана', exact: true })
  await plan.getByLabel('Калорийная цель, ккал/сутки (необязательно)', { exact: true }).fill('1800')
  await plan.getByLabel('Способ оценки суточного расхода', { exact: true }).selectOption('manual')
  await plan.getByLabel('Общая ручная оценка расхода, ккал/сутки', { exact: true }).fill('2000')
  await plan.getByLabel('Источник оценки расхода (необязательно)', { exact: true }).fill('Синтетическая общая оценка, включая активность')
  await plan.getByRole('button', { name: 'Сохранить новую версию', exact: true }).click()
  const history = page.getByRole('list', { name: 'Версии энергетического плана', exact: true })
  await expect(history.getByRole('listitem')).toHaveCount(1)
  const firstVersion = history.getByRole('listitem').filter({ hasText: 'Версия 1, действует с 2026-10-14' })
  await expect(firstVersion).toContainText('Общая ручная оценка: 2000 ккал/сутки.')
  await expect(firstVersion).toContainText('рост 170 см; вес 70 кг от 2026-10-12; возраст 30 лет')
  await expect(plan.getByLabel('Дата начала действия плана', { exact: true })).toBeFocused()
  await navigation.getByRole('link', { name: 'Активность', exact: true }).click()
  await expect(page.getByText('Шаги за этот день: нет данных', { exact: true })).toBeVisible()
  const steps = page.getByLabel('Шаги за день', { exact: true })
  await steps.fill('0')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(page.getByText('Шаги за этот день: 0', { exact: true })).toBeVisible()
  await steps.fill('1234')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(page.getByText(/^Шаги за этот день: 1\s234$/)).toBeVisible()
  const add = page.getByRole('form', { name: 'Добавление тренировки', exact: true })
  const manualKind = 'Синтетическая прогулка'
  const unknownKind = 'Синтетическая растяжка'
  await add.getByLabel('Вид тренировки', { exact: true }).fill(manualKind)
  await add.getByLabel('Длительность, мин', { exact: true }).fill('30')
  await add.getByLabel('Ручная оценка расхода, ккал (необязательно)', { exact: true }).fill('400')
  await add.getByLabel('Источник оценки (необязательно)', { exact: true }).fill('Синтетическая ручная оценка')
  await add.getByRole('button', { name: 'Добавить тренировку', exact: true }).click()
  const workouts = page.getByRole('list', { name: 'Тренировки выбранного дня', exact: true })
  await expect(workouts).toContainText('Ручная оценка: 400 ккал')
  await expect(add.getByLabel('Вид тренировки', { exact: true })).toBeFocused()
  await add.getByLabel('Вид тренировки', { exact: true }).fill(unknownKind)
  await add.getByLabel('Длительность, мин', { exact: true }).fill('10,5')
  await add.getByRole('button', { name: 'Добавить тренировку', exact: true }).click()
  await expect(workouts.getByRole('listitem')).toHaveCount(2)
  await expect(workouts.getByRole('listitem').filter({ hasText: unknownKind })).toContainText('10,5 мин. Расход: нет данных')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await navigation.getByRole('link', { name: 'Сегодня', exact: true }).click()
  const energy = page.getByRole('region', { name: 'Цель и оценочный баланс', exact: true })
  const activity = page.getByRole('region', { name: 'Активность за день', exact: true })
  await expect(energy.getByText('Общая оценка расхода: 2000 ккал.', { exact: true })).toBeVisible()
  await expect(energy.getByText('Расход минус питание: нет данных.', { exact: true })).toBeVisible()
  await expect(activity.getByText(/^Шаги: 1\s234\.$/)).toBeVisible()
  await expect(activity).toContainText('10,5 мин; ручная оценка: нет данных')
  const complete = page.getByRole('region', { name: 'Итоги питания', exact: true }).getByRole('checkbox', { name: 'За этот день внесена вся еда', exact: true })
  await complete.click()
  await expect(complete).toBeChecked()
  await expect(energy.getByText('Цель: 1800 ккал. Внесённая еда: 0 ккал.', { exact: true })).toBeVisible()
  await expect(energy.getByText(/^Расход минус питание: 2\s000 ккал\.$/)).toBeVisible()
  await navigation.getByRole('link', { name: 'Активность', exact: true }).click()
  const editButton = workouts.getByRole('button', { name: `Изменить тренировку 1: ${manualKind}`, exact: true })
  const edit = page.getByRole('form', { name: 'Редактирование тренировки', exact: true })
  await editButton.click()
  await expect(edit.getByLabel('Дата тренировки', { exact: true })).toBeFocused()
  await expect(edit.getByLabel('Ручная оценка расхода, ккал (необязательно)', { exact: true })).toHaveValue('400')
  await edit.getByLabel('Длительность, мин', { exact: true }).fill('99')
  await edit.getByRole('button', { name: 'Отменить правку тренировки', exact: true }).click()
  await expect(workouts).toContainText('30 мин. Ручная оценка: 400 ккал')
  await expect(add.getByLabel('Вид тренировки', { exact: true })).toBeFocused()
  await editButton.click()
  await edit.getByLabel('Длительность, мин', { exact: true }).fill('60,5')
  await edit.getByLabel('Ручная оценка расхода, ккал (необязательно)', { exact: true }).fill('450,25')
  await edit.getByLabel('Комментарий к тренировке (необязательно)', { exact: true }).fill('Синтетическая правка без изменения общего плана')
  await page.keyboard.press('Tab')
  await expect(edit.getByRole('button', { name: 'Сохранить тренировку', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(workouts).toContainText('60,5 мин. Ручная оценка: 450,25 ккал')
  const remove = workouts.getByRole('button', { name: `Удалить тренировку 2: ${unknownKind}`, exact: true })
  await remove.click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog.getByRole('button', { name: 'Отмена', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(workouts.getByRole('listitem')).toHaveCount(2)
  await remove.click()
  await dialog.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect(workouts.getByRole('listitem')).toHaveCount(1)
  await expect(add.getByLabel('Вид тренировки', { exact: true })).toBeFocused()
  await navigation.getByRole('link', { name: 'Сегодня', exact: true }).click()
  await expect(energy.getByText('Общая оценка расхода: 2000 ккал.', { exact: true })).toBeVisible()
  await expect(energy.getByText(/^Расход минус питание: 2\s000 ккал\.$/)).toBeVisible()
  await expect(activity).toContainText('60,5 мин; ручная оценка: 450,25 ккал')
  await navigation.getByRole('link', { name: 'Настройки', exact: true }).click()
  await plan.getByLabel('Калорийная цель, ккал/сутки (необязательно)', { exact: true }).fill('1800')
  await plan.getByLabel('Способ оценки суточного расхода', { exact: true }).selectOption('factor')
  await plan.getByLabel('Ваш коэффициент активности', { exact: true }).fill('1,4')
  await plan.getByRole('button', { name: 'Сохранить новую версию', exact: true }).click()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  const secondVersion = history.getByRole('listitem').filter({ hasText: 'Версия 2, действует с 2026-10-14' })
  await expect(secondVersion).toContainText(/Коэффициент активности: 1,4\. Расход в покое \(оценка\): 1\s618 ккал/)
  await navigation.getByRole('link', { name: 'Профиль', exact: true }).click()
  await page.getByRole('button', { name: 'Редактировать профиль', exact: true }).click()
  await page.getByLabel('Рост, см', { exact: true }).fill('180')
  await page.getByRole('button', { name: 'Сохранить профиль', exact: true }).click()
  await expect(page.getByText('180 см', { exact: true })).toBeVisible()
  await navigation.getByRole('link', { name: 'Настройки', exact: true }).click()
  await expect(firstVersion).toContainText('рост 170 см; вес 70 кг')
  await expect(secondVersion).toContainText('рост 170 см; вес 70 кг')
  await plan.getByLabel('Дата начала действия плана', { exact: true }).fill('2026-10-15')
  await plan.getByLabel('Способ оценки суточного расхода', { exact: true }).selectOption('manual')
  await plan.getByLabel('Общая ручная оценка расхода, ккал/сутки', { exact: true }).fill('2222')
  await plan.getByRole('button', { name: 'Сохранить новую версию', exact: true }).click()
  await expect(history.getByRole('listitem')).toHaveCount(3)
  await expect(history.getByRole('listitem').filter({ hasText: 'Версия 3, действует с 2026-10-15' })).toContainText('рост 180 см; вес 70 кг')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await navigation.getByRole('link', { name: 'Сегодня', exact: true }).click()
  await expect(energy.getByText(/^Общая оценка расхода: 2\s264,5 ккал\.$/)).toBeVisible()
  await expect(energy).toContainText('Версия 2, действует с 2026-10-14')
  const picker = page.getByRole('form', { name: 'Выбор дня', exact: true })
  await picker.getByLabel('День дневника', { exact: true }).fill('2026-10-13')
  await picker.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(energy.getByText('Общая оценка расхода: нет данных.', { exact: true })).toBeVisible()
  await expect(energy).toContainText('Для этого дня план не задан.')
  await picker.getByRole('button', { name: 'Сегодня', exact: true }).click()
  await expect(energy.getByText(/^Общая оценка расхода: 2\s264,5 ккал\.$/)).toBeVisible()
  await page.reload()
  await expect(energy.getByText(/^Общая оценка расхода: 2\s264,5 ккал\.$/)).toBeVisible()
  await expect(energy.getByText(/^Расход минус питание: 2\s264,5 ккал\.$/)).toBeVisible()
  await expect(activity.getByText(/^Шаги: 1\s234\.$/)).toBeVisible()
  await expect(activity.getByRole('list', { name: 'Сводка тренировок', exact: true }).getByRole('listitem')).toHaveCount(1)
  await expect(activity).toContainText('60,5 мин; ручная оценка: 450,25 ккал')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
