import { expect, test, type Page } from '@playwright/test'
import axe from 'axe-core'

test.use({ timezoneId: 'Europe/Moscow' })
const failures = new WeakMap<Page, string[]>()

async function openDay(page: Page, date: string) {
  await page.getByLabel('День дневника', { exact: true }).fill(date)
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(page.getByText(`Открыт день: ${date.split('-').reverse().join('.')}`, { exact: true })).toBeVisible()
}

test.beforeEach(async ({ page, baseURL }) => {
  const errors: string[] = []
  failures.set(page, errors)
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => {
    const url = new URL(request.url())
    if (['http:', 'https:'].includes(url.protocol) && url.origin !== baseURL) errors.push(url.href)
  })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
})

test.afterEach(async ({ page }) => {
  await page.addScriptTag({ content: axe.source })
  expect(await page.evaluate(async () => (await window.axe.run(document)).violations)).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(failures.get(page)).toEqual([])
})

test('графики БЖУ меняются с порцией и датой, различают ноль и неизвестный состав', async ({ page }) => {
  await page.goto('/#nutrition')
  const charts = page.getByRole('region', { name: 'Белки, жиры и углеводы', exact: true })
  await expect(charts.getByText('За выбранный день · по записанным продуктам и порциям')).toBeVisible()
  await expect(charts.getByRole('meter')).toHaveCount(0)
  const product = page.getByRole('form', { name: 'Новый продукт', exact: true })
  await product.getByLabel('Название продукта').fill('Учебный продукт БЖУ')
  await product.getByLabel('Калории на 100 г, ккал').fill('200')
  await product.getByLabel('Белки на 100 г, г (необязательно)').fill('12')
  await product.getByLabel('Углеводы на 100 г, г (необязательно)').fill('0')
  await product.getByRole('button', { name: 'Сохранить продукт' }).click()
  const food = page.getByRole('form', { name: 'Добавление еды', exact: true })
  await food.getByLabel('Продукт для записи').selectOption({ label: 'Учебный продукт БЖУ' })
  await food.getByLabel('Приём пищи', { exact: true }).selectOption('breakfast')
  await food.getByLabel('Масса порции, г').fill('150')
  await food.getByRole('button', { name: 'Добавить еду' }).click()
  const protein = charts.getByRole('meter', { name: 'Белки за день', exact: true })
  await expect(protein).toHaveAttribute('aria-valuetext', '18 г')
  await expect(charts.getByRole('meter', { name: 'Завтрак: Белки', exact: true })).toHaveAttribute('value', '18')
  await expect(charts.getByRole('meter', { name: 'Углеводы за день', exact: true })).toHaveAttribute('value', '0')
  await expect(charts.getByRole('meter', { name: 'Жиры за день', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Изменить запись еды 1: Учебный продукт БЖУ', exact: true }).click()
  const edit = page.getByRole('form', { name: 'Редактирование еды', exact: true })
  await edit.getByLabel('Масса порции, г').fill('125')
  await edit.getByRole('button', { name: 'Сохранить запись еды' }).click()
  await expect(protein).toHaveAttribute('value', '15')
  await page.reload()
  await expect(protein).toHaveAttribute('value', '15')
  await openDay(page, '2026-10-13')
  await expect(charts.getByRole('meter')).toHaveCount(0)
  const complete = page.getByRole('checkbox', { name: 'За этот день внесена вся еда', exact: true })
  await complete.click()
  await expect(complete).toBeChecked()
  await expect(protein).toHaveAttribute('value', '0')
  await expect(charts.getByRole('meter', { name: 'Жиры за день', exact: true })).toHaveAttribute('value', '0')
  await openDay(page, '2026-10-14')
  await expect(protein).toHaveAttribute('value', '15')
  await expect(charts.getByRole('meter', { name: 'Жиры за день', exact: true })).toHaveCount(0)
})

test('недельный график шагов сохраняет пропуски и ноль, обновляется при правке и смене дня', async ({ page }) => {
  await page.goto('/#activity')
  const week = page.getByRole('region', { name: 'Шаги за семь дней', exact: true })
  const days = week.getByRole('listitem')
  await expect(days).toHaveCount(7)
  await expect(week.getByText('Нет записи', { exact: true })).toHaveCount(7)
  await page.getByLabel('Шаги за день', { exact: true }).fill('7200')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  const today = days.filter({ hasText: '14.10' })
  await expect(today).toContainText(/7\s200/)
  await expect(week).toContainText(/Шкала от 0 до 7\s200 шагов/)
  await openDay(page, '2026-10-13')
  await expect(days.filter({ hasText: '14.10' })).toHaveCount(0)
  await page.getByLabel('Шаги за день', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(days.filter({ hasText: '13.10' }).getByText('0', { exact: true })).toBeVisible()
  await expect(week.getByText('Нет записи', { exact: true })).toHaveCount(6)
  await openDay(page, '2026-10-14')
  await expect(today).toContainText(/7\s200/)
  await expect(week.getByText('Нет записи', { exact: true })).toHaveCount(5)
  await page.getByLabel('Шаги за день', { exact: true }).fill('3600')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(today).toContainText(/3\s600/)
  await page.reload()
  await expect(today).toContainText(/3\s600/)
  await expect(week).toContainText(/Шкала от 0 до 3\s600 шагов/)
  await expect(days.filter({ hasText: '13.10' }).getByText('0', { exact: true })).toBeVisible()
  await expect(week.getByText('Нет записи', { exact: true })).toHaveCount(5)
})
