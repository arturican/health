import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures'

test.use({ timezoneId: 'Europe/Moscow' })

test('PDF скачивается без изменения байтов, показатели правятся и удаляются отдельно и вместе с бланком', async ({ page, baseURL }, info) => {
  const errors: string[] = []
  const deletedResources = new Set<string>()
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => {
    if (message.type() !== 'error') return
    // In-flight reads of the exact resource just deleted may finish with 404.
    if (deletedResources.has(message.location().url) && message.text() === 'Failed to load resource: the server responded with a status of 404 (Not Found)') return
    errors.push(message.text())
  })
  page.on('request', request => { if (new URL(request.url()).origin !== baseURL) external.push(request.url()) })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#documents')
  const originalTitle = 'Синтетический анализ PDF'
  const editedTitle = 'Синтетическая выписка PDF с длинным названием'
  const bytes = Buffer.from('%PDF-1.7\nsynthetic-original-laboratory-document\n%%EOF\n')
  const addDocument = page.getByRole('form', { name: 'Добавление документа', exact: true })
  await addDocument.getByLabel('Название документа', { exact: true }).fill(originalTitle)
  await addDocument.getByLabel('Заметка к документу (необязательно)', { exact: true }).fill('Синтетическая исходная заметка')
  await addDocument.getByLabel('Файл документа', { exact: true }).setInputFiles({ name: 'synthetic-source.pdf', mimeType: 'application/pdf', buffer: bytes })
  await addDocument.getByRole('button', { name: 'Добавить документ', exact: true }).click()
  const documents = page.getByRole('list', { name: 'Сохранённые документы', exact: true })
  await expect(documents.getByRole('heading', { level: 3, name: originalTitle, exact: true })).toBeVisible()
  await expect(addDocument.getByLabel('Название документа', { exact: true })).toBeFocused()
  const downloadReady = page.waitForEvent('download')
  await documents.getByRole('button', { name: `Скачать оригинал: ${originalTitle}`, exact: true }).click()
  const originalDownload = await downloadReady
  const safeFilename = originalDownload.suggestedFilename()
  expect(safeFilename).toMatch(/^health-document-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.pdf$/i)
  const originalPath = info.outputPath('synthetic-original-document.pdf')
  await originalDownload.saveAs(originalPath)
  expect(await originalDownload.failure()).toBeNull()
  expect(await readFile(originalPath)).toEqual(bytes)
  await expect(page.locator('iframe, object, embed')).toHaveCount(0)
  const editor = page.getByRole('form', { name: 'Редактирование документа', exact: true })
  const editDocument = documents.getByRole('button', { name: `Изменить документ 1: ${originalTitle}`, exact: true })
  await editDocument.click()
  await expect(editor.getByLabel('Дата документа', { exact: true })).toBeFocused()
  await expect(editor.getByLabel('Название документа', { exact: true })).toHaveValue(originalTitle)
  await expect(editor.getByLabel('Файл документа', { exact: true })).toHaveCount(0)
  await editor.getByLabel('Название документа', { exact: true }).fill('Отменённая синтетическая правка')
  await editor.getByRole('button', { name: 'Отменить правку документа', exact: true }).click()
  await expect(documents.getByRole('heading', { level: 3, name: originalTitle, exact: true })).toBeVisible()
  await editDocument.click()
  await editor.getByLabel('Дата документа', { exact: true }).fill('2026-10-13')
  await editor.getByLabel('Название документа', { exact: true }).fill(editedTitle)
  await editor.getByLabel('Категория документа', { exact: true }).selectOption('report')
  await editor.getByLabel('Заметка к документу (необязательно)', { exact: true }).fill('Синтетическая новая заметка')
  await page.keyboard.press('Tab')
  await expect(editor.getByRole('button', { name: 'Сохранить документ', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(documents.getByRole('heading', { level: 3, name: editedTitle, exact: true })).toBeVisible()
  const search = page.getByLabel('Найти документ', { exact: true })
  await search.fill('  ВЫПИСКА  ')
  await expect(documents.getByRole('listitem')).toHaveCount(1)
  await expect(documents).toContainText('2026-10-13 · Выписка')
  await search.fill(originalTitle)
  await expect(page.getByText('По запросу ничего не найдено.', { exact: true })).toBeVisible()
  await search.fill('  СИНТЕТИЧЕСКАЯ НОВАЯ ЗАМЕТКА  ')
  await expect(documents.getByRole('heading', { level: 3, name: editedTitle, exact: true })).toBeVisible()
  await search.fill('')
  const source = page.getByLabel('Бланк для показателей', { exact: true })
  await source.selectOption({ label: `2026-10-13 — ${editedTitle}` })
  const addLab = page.getByRole('form', { name: 'Добавление показателя', exact: true })
  const numberName = 'Синтетический нулевой показатель'
  const textName = 'Синтетический текстовый показатель'
  const reference = '≤ 0,0000002; как на бланке — без интерпретации'
  await addLab.getByLabel('Дата показателя', { exact: true }).fill('2026-10-12')
  await addLab.getByLabel('Название показателя', { exact: true }).fill(numberName)
  await addLab.getByLabel('Знак сравнения', { exact: true }).selectOption('lte')
  await addLab.getByLabel('Результат числом', { exact: true }).fill('0')
  await addLab.getByLabel('Референс как на бланке (необязательно)', { exact: true }).fill(reference)
  await addLab.getByRole('button', { name: 'Добавить показатель', exact: true }).click()
  const labs = page.getByRole('list', { name: 'Показатели выбранного документа', exact: true })
  const numericRow = labs.getByRole('article', { name: `${numberName}, 2026-10-12`, exact: true })
  await expect(numericRow).toContainText('Результат: ≤ 0')
  await expect(numericRow).toContainText('Единицы: не указаны')
  await expect(numericRow).toContainText(`Референс на бланке: ${reference}`)
  await addLab.getByLabel('Название показателя', { exact: true }).fill(textName)
  await addLab.getByLabel('Формат результата', { exact: true }).selectOption('text')
  await addLab.getByLabel('Результат текстом', { exact: true }).fill('Не обнаружено (синтетический образец)')
  await addLab.getByLabel('Референс как на бланке (необязательно)', { exact: true }).fill('Точный текст синтетического бланка')
  await addLab.getByRole('button', { name: 'Добавить показатель', exact: true }).click()
  await expect(labs.getByRole('listitem')).toHaveCount(2)
  const textRow = labs.getByRole('article', { name: `${textName}, 2026-10-13`, exact: true })
  await expect(textRow).toContainText('Не обнаружено (синтетический образец)')
  await expect(textRow).toContainText('Единицы: не указаны')
  const editLab = page.getByRole('form', { name: 'Редактирование показателя', exact: true })
  await numericRow.getByRole('button', { name: /^Изменить показатель / }).click()
  await expect(editLab.getByLabel('Результат числом', { exact: true })).toHaveValue('0')
  await expect(source).toBeDisabled()
  await editLab.getByLabel('Результат числом', { exact: true }).fill('999')
  await editLab.getByRole('button', { name: 'Отменить правку показателя', exact: true }).click()
  await expect(numericRow).toContainText('Результат: ≤ 0')
  await numericRow.getByRole('button', { name: /^Изменить показатель / }).click()
  await editLab.getByLabel('Дата показателя', { exact: true }).fill('2026-10-14')
  await editLab.getByLabel('Результат числом', { exact: true }).fill('-0,0000001')
  await editLab.getByLabel('Знак сравнения', { exact: true }).selectOption('gte')
  await editLab.getByRole('button', { name: 'Сохранить показатель', exact: true }).click()
  const editedNumericRow = labs.getByRole('article', { name: `${numberName}, 2026-10-14`, exact: true })
  await expect(editedNumericRow).toContainText('Результат: ≥ -0,0000001')
  await expect(editedNumericRow).toContainText(`Референс на бланке: ${reference}`)
  const removeText = textRow.getByRole('button', { name: /^Удалить показатель / })
  const dialog = page.getByRole('alertdialog')
  await removeText.click()
  await expect(dialog.getByRole('button', { name: 'Отмена', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(textRow).toBeVisible()
  await removeText.click()
  await dialog.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect(labs.getByRole('listitem')).toHaveCount(1)
  await expect(page.getByRole('heading', { level: 3, name: 'Записанные показатели', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.reload()
  await source.selectOption({ label: `2026-10-13 — ${editedTitle}` })
  await expect(editedNumericRow).toContainText('Результат: ≥ -0,0000001')
  const editedDownloadReady = page.waitForEvent('download')
  await documents.getByRole('button', { name: `Скачать оригинал: ${editedTitle}`, exact: true }).click()
  const editedDownload = await editedDownloadReady
  expect(editedDownload.suggestedFilename()).toBe(safeFilename)
  const editedPath = info.outputPath('synthetic-edited-document.pdf')
  await editedDownload.saveAs(editedPath)
  expect(await readFile(editedPath)).toEqual(bytes)
  const removeDocument = documents.getByRole('button', { name: `Удалить документ 1: ${editedTitle}`, exact: true })
  await removeDocument.click()
  await expect(dialog).toContainText(`Удалить документ «${editedTitle}» за 2026-10-13, его файл и показатели (1)?`)
  await expect(dialog.getByRole('button', { name: 'Отмена', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(removeDocument).toBeFocused()
  await expect(editedNumericRow).toBeVisible()
  await removeDocument.click()
  const documentId = await source.inputValue()
  const fileId = safeFilename.replace('health-document-', '').replace('.pdf', '')
  for (const path of ['/api/v1/files/' + fileId, '/api/v1/documents/' + documentId + '/results-count', '/api/v1/lab-results?documentId=' + documentId + '&limit=100']) {
    deletedResources.add(new URL(path, baseURL).href)
  }
  await dialog.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect(page.getByText('Документов пока нет.', { exact: true })).toBeVisible()
  await expect(labs).toHaveCount(0)
  await expect(source).toHaveCount(0)
  await expect(page.getByRole('heading', { level: 2, name: 'Документы по датам', exact: true })).toBeFocused()
  await page.reload()
  await expect(page.getByText('Документов пока нет.', { exact: true })).toBeVisible()
  await expect(page.getByText('Сначала добавьте документ-источник.', { exact: true })).toBeVisible()
  await expect(documents).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
