import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Europe/Moscow' })

test('скачанный файл восстанавливает изменённый профиль после согласия и перезагрузки', async ({ page, baseURL }, info) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { if (new URL(request.url()).origin !== baseURL) external.push(request.url()) })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#profile')
  await page.getByLabel('Имя (необязательно)').fill('Синтетическая копия')
  await page.getByLabel('Рост, см').fill('170')
  await page.getByLabel('Вес, кг').fill('70')
  await page.getByRole('button', { name: 'Создать профиль' }).click()
  await expect(page.getByRole('status')).toHaveText('Профиль и первое измерение сохранены')
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  const downloadReady = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать текстовую копию', exact: true }).click()
  const download = await downloadReady
  expect(download.suggestedFilename()).toBe('health-diary-text-2026-10-14.json')
  const path = info.outputPath('synthetic-text-backup.json')
  await download.saveAs(path)
  expect(await download.failure()).toBeNull()
  await page.getByRole('link', { name: 'Профиль', exact: true }).click()
  await page.getByRole('button', { name: 'Редактировать профиль' }).click()
  await page.getByLabel('Рост, см').fill('180')
  await page.getByRole('button', { name: 'Сохранить профиль' }).click()
  await expect(page.getByText('180 см', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.getByLabel('Файл текстовой копии').setInputFiles(path)
  await page.getByRole('button', { name: 'Проверить файл', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Предпросмотр текстовой копии' })).toBeVisible()
  const restore = page.getByRole('button', { name: 'Восстановить текстовую копию', exact: true })
  await expect(restore).toBeDisabled()
  await page.getByLabel('Согласен заменить текстовые данные дневника').check()
  await restore.click()
  await expect(page.getByRole('status')).toHaveText('Текстовая копия восстановлена')
  await page.reload()
  await page.getByRole('link', { name: 'Профиль', exact: true }).click()
  await expect(page.getByText('170 см', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Вес', exact: true }).click()
  await expect(page.getByRole('list', { name: 'История веса' }).getByRole('listitem')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
