import { expect, test } from '@playwright/test'

test('пустая production-сводка показывает неизвестные данные без ошибок, внешних запросов и переполнения', async ({ page, baseURL }) => {
  const errors: string[] = []
  const externalRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error') errors.push(message.text())
  })
  page.on('request', request => {
    if (new URL(request.url()).origin !== baseURL) externalRequests.push(request.url())
  })

  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/')
  await expect(page).toHaveTitle('Дневник здоровья')
  await expect(page.getByRole('heading', { level: 1, name: 'Сегодня' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Начните с профиля' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Заполнить профиль' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Последнее измерение веса' })).toHaveText(/Нет измерений не позже выбранного дня/)
  await expect(page.getByRole('region', { name: 'ИМТ (справочно)' })).toHaveText(/Нужны рост в профиле и измерение веса/)
  const food = page.getByRole('region', { name: 'Итоги питания' })
  await expect(food.getByText('Калории: нет данных', { exact: true })).toBeVisible()
  await expect(food.getByRole('checkbox', { name: 'За этот день внесена вся еда' })).not.toBeChecked()
  const energy = page.getByRole('region', { name: 'Цель и оценочный баланс' })
  await expect(energy.getByText('Цель: нет данных. Внесённая еда: нет данных.', { exact: true })).toBeVisible()
  await expect(energy.getByText('Расход минус питание: нет данных.', { exact: true })).toBeVisible()
  const activity = page.getByRole('region', { name: 'Активность за день' })
  await expect(activity.getByText('Шаги: нет данных.', { exact: true })).toBeVisible()
  await expect(activity.getByText('Тренировки не записаны.', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Записать еду', exact: true })).toHaveAttribute('href', '#nutrition')
  await expect(page.getByRole('link', { name: 'Открыть активность', exact: true })).toHaveAttribute('href', '#activity')

  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflows).toBe(false)
  expect(errors).toEqual([])
  expect(externalRequests).toEqual([])
})

test('клавиатура открывает реальные журналы, сохраняет выбранный день и возвращает фокус при навигации', async ({ page, baseURL }) => {
  const errors: string[] = []
  const externalRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error') errors.push(message.text())
  })
  page.on('request', request => {
    if (new URL(request.url()).origin !== baseURL) externalRequests.push(request.url())
  })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#today')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Перейти к содержимому' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#today$/)
  await expect(page.getByRole('main')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('День дневника')).toBeFocused()
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('Открыт день: 13.10.2026', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Записать вес', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#weight$/)
  await expect(page.getByRole('heading', { name: 'Вес', level: 1 })).toBeVisible()
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('link', { name: 'Перейти к содержимому' }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#weight$/)
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('link', { name: 'создайте профиль' }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#profile$/)
  await expect(page.getByRole('form', { name: 'Создание профиля' })).toBeVisible()
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByLabel('Имя (необязательно)').fill('Синтетический профиль')
  await page.getByLabel('Рост, см').fill('170')
  await page.getByLabel('Вес, кг').fill('70')
  await page.getByLabel('Дата первого измерения').fill('2026-10-12')
  await page.getByRole('button', { name: 'Создать профиль' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('Профиль и первое измерение сохранены')
  await page.getByRole('navigation', { name: 'Разделы дневника' }).getByRole('link', { name: 'Сегодня', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#today$/)
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-13')
  await expect(page.getByRole('region', { name: 'Последнее измерение веса' })).toHaveText(/70 кг, измерено 12\.10\.2026/)
  await expect(page.getByRole('region', { name: 'Начните с профиля' })).toHaveCount(0)
  await page.goBack()
  await expect(page).toHaveURL(/#profile$/)
  await expect(page.getByRole('heading', { name: 'Профиль', level: 1 })).toBeVisible()
  await expect(page.getByRole('main')).toBeFocused()
  await page.goForward()
  await expect(page).toHaveURL(/#today$/)
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-13')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(externalRequests).toEqual([])
})
