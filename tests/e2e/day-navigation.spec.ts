import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Europe/Moscow' })

test('выбор дня согласует журналы, исторический вес и полноту, а график показывает реальные измерения', async ({ page, baseURL }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { if (new URL(request.url()).origin !== baseURL) external.push(request.url()) })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/#profile')
  await page.getByLabel('Имя (необязательно)').fill('Синтетический календарь')
  await page.getByLabel('Рост, см').fill('180')
  await page.getByLabel('Дата рождения (необязательно)').fill('1990-01-01')
  await page.getByLabel('Вес, кг').fill('70')
  await page.getByLabel('Дата первого измерения').fill('2026-10-12')
  await page.getByRole('button', { name: 'Создать профиль', exact: true }).click()
  await expect(page.getByText('Профиль и первое измерение сохранены', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Вес', exact: true }).click()
  await page.getByLabel('Вес, кг').fill('72')
  await page.getByRole('button', { name: 'Сохранить вес', exact: true }).click()
  const chart = page.getByRole('region', { name: 'График веса', exact: true })
  await expect(chart.getByRole('img')).toHaveAccessibleDescription(/от 12.10.2026 до 14.10.2026; диапазон 70–72 кг/)
  await expect(chart.getByText('Период: 12.10.2026 — 14.10.2026.', { exact: true })).toBeVisible()
  await expect(page.getByRole('list', { name: 'История веса' }).getByRole('listitem')).toHaveCount(2)

  await page.getByRole('link', { name: 'Активность', exact: true }).click()
  await page.getByLabel('Шаги за день').fill('100')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(page.getByText('Шаги за этот день: 100', { exact: true })).toBeVisible()
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(page.getByText('Шаги за этот день: нет данных', { exact: true })).toBeVisible()
  await page.getByLabel('Шаги за день').fill('0')
  await page.getByRole('button', { name: 'Сохранить шаги', exact: true }).click()
  await expect(page.getByText('Шаги за этот день: 0', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Сегодня', exact: true }).click()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-13')
  await expect(page.getByText('70 кг, измерено 12.10.2026.', { exact: true })).toBeVisible()
  await expect(page.getByText('Шаги: 0.', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Питание', exact: true }).click()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-13')
  const complete = page.getByLabel('За этот день внесена вся еда')
  await expect(complete).not.toBeChecked()
  await expect(page.getByText('Калории: нет данных', { exact: true })).toBeVisible()
  await complete.click()
  await expect(complete).toBeChecked()
  await expect(page.getByText('Вся еда за день внесена.', { exact: true })).toBeVisible()
  await expect(page.getByText('Калории: 0 ккал', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Сегодня', exact: true }).click()
  await expect(complete).toBeChecked()
  await expect(page.getByText('Калории: 0 ккал', { exact: true })).toBeVisible()
  await expect(page.getByText('70 кг, измерено 12.10.2026.', { exact: true })).toBeVisible()

  await page.getByLabel('День дневника').fill('2026-10-11')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(page.getByText('Нет измерений не позже выбранного дня.', { exact: true })).toBeVisible()
  await expect(page.getByText('Шаги: нет данных.', { exact: true })).toBeVisible()
  await expect(complete).not.toBeChecked()
  await expect(page.getByText('Калории: нет данных', { exact: true })).toBeVisible()
  await page.getByLabel('День дневника').fill('2026-10-15')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(page.getByLabel('День дневника')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('День дневника')).toBeFocused()
  await expect(page.getByText('Открыт день: 11.10.2026', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Сегодня', exact: true }).click()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-14')
  await expect(page.getByText('72 кг, измерено 14.10.2026.', { exact: true })).toBeVisible()
  await expect(page.getByText('Шаги: 100.', { exact: true })).toBeVisible()

  await page.reload()
  await expect(page.getByText('72 кг, измерено 14.10.2026.', { exact: true })).toBeVisible()
  await page.getByLabel('День дневника').fill('2026-10-13')
  await page.getByRole('button', { name: 'Открыть день', exact: true }).click()
  await expect(complete).toBeChecked()
  await expect(page.getByText('Шаги: 0.', { exact: true })).toBeVisible()
  await expect(page.getByText('70 кг, измерено 12.10.2026.', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Активность', exact: true }).click()
  await expect(page.getByLabel('День дневника')).toHaveValue('2026-10-13')
  await expect(page.getByText('Шаги за этот день: 0', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
