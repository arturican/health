import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Europe/Moscow' })

test('профиль и журнал веса сохраняются после перезагрузки и меняются только по действиям пользователя', async ({ page, baseURL }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { if (new URL(request.url()).origin !== baseURL) external.push(request.url()) })
  await page.clock.setFixedTime(new Date('2026-10-14T12:00:00Z'))
  await page.goto('/')
  await page.getByRole('link', { name: 'Профиль', exact: true }).click()
  await page.getByLabel('Имя (необязательно)').fill('Синтетический профиль')
  await page.getByLabel('Рост, см').fill('180')
  await page.getByLabel('Дата рождения (необязательно)').fill('2000-01-01')
  await page.getByLabel('Вес, кг').fill('72')
  await page.getByLabel('Дата первого измерения').fill('2026-10-12')
  await page.getByRole('button', { name: 'Создать профиль' }).click()
  await expect(page.getByRole('status')).toHaveText('Профиль и первое измерение сохранены')
  await page.getByRole('link', { name: 'Вес', exact: true }).click()
  const bmi = page.getByRole('region', { name: 'ИМТ (справочно)' })
  const history = page.getByRole('list', { name: 'История веса' })
  await expect(bmi.getByText('22,2', { exact: true })).toBeVisible()
  await page.getByLabel('Вес, кг').fill('73,5')
  await page.getByRole('button', { name: 'Сохранить вес' }).click()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await expect(bmi.getByText('22,7', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: 'Вес' })).toBeVisible()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await expect(bmi.getByText('22,7', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Перейти к содержимому' }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#weight$/)
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('link', { name: 'Профиль', exact: true }).click()
  await page.getByRole('button', { name: 'Редактировать профиль' }).click()
  await page.getByLabel('Рост, см').fill('200')
  await page.getByRole('button', { name: 'Сохранить профиль' }).click()
  await expect(page.getByText('200 см', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Вес', exact: true }).click()
  await expect(bmi.getByText('18,4', { exact: true })).toBeVisible()
  await expect(history.getByRole('listitem')).toHaveCount(2)

  await page.getByLabel('Вес, кг').fill('0')
  await page.getByRole('button', { name: 'Сохранить вес' }).click()
  await expect(page.getByLabel('Вес, кг')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('Вес, кг')).toBeFocused()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await page.getByLabel('Вес, кг').fill('74')
  await page.getByRole('button', { name: 'Сохранить вес' }).click()
  await expect(bmi.getByText('18,5', { exact: true })).toBeVisible()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await page.getByRole('button', { name: 'Изменить вес за 14.10.2026' }).click()
  await page.getByLabel('Дата измерения').fill('2026-10-13')
  await page.getByRole('button', { name: 'Сохранить вес' }).click()
  await expect(page.getByRole('button', { name: 'Удалить вес за 13.10.2026' })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить вес за 13.10.2026' }).click()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(history.getByRole('listitem')).toHaveCount(2)
  await page.getByRole('button', { name: 'Удалить вес за 13.10.2026' }).click()
  await page.getByRole('button', { name: 'Подтвердить удаление' }).click()
  await expect(history.getByRole('listitem')).toHaveCount(1)
  await page.reload()
  await expect(history.getByRole('listitem')).toHaveCount(1)
  await expect(bmi.getByText('18,0', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
