import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { page, userEvent } from 'vitest/browser'
import { cleanup, render } from 'vitest-browser-react'
import axe from 'axe-core'
import { App } from '../App'
import { db } from '../data/db'
import '../styles.css'

async function resetTestState() {
  await cleanup()
  expect(import.meta.env.MODE).toBe('test')
  expect(db.name).toBe('health-diary-tests')
  await db.transaction('rw', db.tables, async () => {
    for (const table of db.tables) await table.clear()
  })
  window.history.replaceState(null, '', window.location.pathname)
}

beforeEach(async () => {
  await resetTestState()
  await page.viewport(375, 812)
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date('2026-10-14T12:00:00.000Z'))
})

afterEach(async () => {
  await resetTestState()
  vi.useRealTimers()
  await page.viewport(1280, 800)
  const externalRequests = performance.getEntriesByType('resource').map(entry => new URL(entry.name)).filter(url =>
    ['http:', 'https:'].includes(url.protocol) && url.origin !== window.location.origin,
  )
  expect(externalRequests).toEqual([])
})

test('вес возвращает фокус после сохранения, правки, отмены и удаления; ошибку удаления можно повторить', async () => {
  const view = await render(<App />)
  await page.getByRole('link', { name: 'Профиль', exact: true }).click()
  await page.getByLabelText('Имя (необязательно)', { exact: true }).fill('Синтетический фокус')
  await page.getByLabelText('Рост, см', { exact: true }).fill('170')
  await page.getByLabelText('Вес, кг', { exact: true }).fill('70')
  await page.getByRole('button', { name: 'Создать профиль', exact: true }).click()
  await expect.element(page.getByText('Синтетический фокус', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Вес', exact: true }).click()
  await page.getByLabelText('Дата измерения', { exact: true }).fill('2026-10-13')
  await page.getByLabelText('Вес, кг', { exact: true }).fill('69,5')
  await page.getByRole('button', { name: 'Сохранить вес', exact: true }).click()
  await expect.element(page.getByRole('button', { name: 'Изменить вес за 13.10.2026', exact: true })).toBeVisible()
  await expect.element(page.getByLabelText('Вес, кг', { exact: true })).toHaveFocus()
  await page.getByRole('button', { name: 'Изменить вес за 13.10.2026', exact: true }).click()
  await expect.element(page.getByLabelText('Дата измерения', { exact: true })).toHaveFocus()
  await page.getByLabelText('Вес, кг', { exact: true }).fill('99')
  await page.getByRole('button', { name: 'Отменить изменение', exact: true }).click()
  await expect.element(page.getByLabelText('Вес, кг', { exact: true })).toHaveFocus()
  expect(await db.weights.where('date').equals('2026-10-13').first()).toMatchObject({ kg: 69.5 })
  await page.getByRole('button', { name: 'Изменить вес за 13.10.2026', exact: true }).click()
  await expect.element(page.getByLabelText('Дата измерения', { exact: true })).toHaveFocus()
  await page.getByLabelText('Дата измерения', { exact: true }).fill('2026-10-12')
  await page.getByLabelText('Вес, кг', { exact: true }).fill('69,25')
  await userEvent.keyboard('{Tab}{Enter}')
  await expect.element(page.getByRole('button', { name: 'Изменить вес за 12.10.2026', exact: true })).toBeVisible()
  await expect.element(page.getByLabelText('Вес, кг', { exact: true })).toHaveFocus()

  const remove = page.getByRole('button', { name: 'Удалить вес за 12.10.2026', exact: true })
  await remove.click()
  await expect.element(page.getByRole('button', { name: 'Отмена', exact: true })).toHaveFocus()
  await userEvent.keyboard('{Enter}')
  await expect.element(remove).toHaveFocus()
  const saved = await db.weights.toArray()
  function failDeletion() { throw new DOMException('Синтетическая ошибка хранилища', 'QuotaExceededError') }
  db.weights.hook('deleting', failDeletion)
  try {
    await remove.click()
    await page.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
    await expect.element(page.getByRole('alert')).toHaveTextContent('Не удалось выполнить действие')
    await expect.element(page.getByRole('alertdialog')).toBeVisible()
    await expect.element(page.getByRole('button', { name: 'Отмена', exact: true })).toHaveFocus()
    expect(await db.weights.toArray()).toEqual(saved)
  } finally {
    db.weights.hook('deleting').unsubscribe(failDeletion)
  }
  await page.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect.element(remove).not.toBeInTheDocument()
  await expect.element(page.getByRole('alertdialog')).not.toBeInTheDocument()
  await expect.element(page.getByLabelText('Вес, кг', { exact: true })).toHaveFocus()
  expect(await db.weights.count()).toBe(1)
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth)
  expect((await axe.run(view.container)).violations).toEqual([])
}, 20000)

test('еда восстанавливает фокус, сохраняет новый черновик при удалении другой строки и использует заголовок без активных продуктов', async () => {
  const view = await render(<App />)
  await page.getByRole('link', { name: 'Питание', exact: true }).click()
  const name = 'Синтетический продукт для фокуса'
  const product = page.getByRole('form', { name: 'Новый продукт', exact: true })
  await product.getByLabelText('Название продукта', { exact: true }).fill(name)
  await product.getByLabelText('Калории на 100 г, ккал', { exact: true }).fill('100')
  await product.getByRole('button', { name: 'Сохранить продукт', exact: true }).click()
  const form = page.getByRole('form', { name: 'Добавление еды', exact: true })
  const select = form.getByLabelText('Продукт для записи', { exact: true })
  for (const [grams, note] of [['100', 'Синтетическая первая порция'], ['200', 'Синтетическая вторая порция']] as const) {
    await select.selectOptions(page.getByRole('option', { name, exact: true }))
    await form.getByLabelText('Масса порции, г', { exact: true }).fill(grams)
    await form.getByLabelText('Комментарий к еде (необязательно)', { exact: true }).fill(note)
    await userEvent.keyboard('{Tab}{Enter}')
    await expect.element(page.getByText(note, { exact: true })).toBeVisible()
    await expect.element(select).toHaveFocus()
  }
  const journal = page.getByRole('list', { name: 'Еда выбранного дня', exact: true })
  const first = journal.getByRole('listitem').filter({ hasText: 'Синтетическая первая порция' })
  const edit = page.getByRole('form', { name: 'Редактирование еды', exact: true })
  await first.getByRole('button', { name: /^Изменить запись еды/ }).click()
  await expect.element(edit.getByLabelText('Дата записи еды', { exact: true })).toHaveFocus()
  await edit.getByLabelText('Масса порции, г', { exact: true }).fill('999')
  await edit.getByRole('button', { name: 'Отменить правку еды', exact: true }).click()
  await expect.element(select).toHaveFocus()
  await expect.element(first).toHaveTextContent('Завтрак · 100 г · 100 ккал')
  await first.getByRole('button', { name: /^Изменить запись еды/ }).click()
  await expect.element(edit.getByLabelText('Дата записи еды', { exact: true })).toHaveFocus()
  await edit.getByLabelText('Масса порции, г', { exact: true }).fill('125')
  await edit.getByRole('button', { name: 'Сохранить запись еды', exact: true }).click()
  await expect.element(first).toHaveTextContent('Завтрак · 125 г · 125 ккал')
  await expect.element(select).toHaveFocus()

  await select.selectOptions(page.getByRole('option', { name, exact: true }))
  await form.getByLabelText('Масса порции, г', { exact: true }).fill('55,55')
  await form.getByLabelText('Комментарий к еде (необязательно)', { exact: true }).fill('Синтетический новый черновик')
  const remove = first.getByRole('button', { name: /^Удалить запись еды/ })
  await remove.click()
  await expect.element(page.getByRole('button', { name: 'Отмена', exact: true })).toHaveFocus()
  await userEvent.keyboard('{Enter}')
  await expect.element(remove).toHaveFocus()
  expect(await db.foodEntries.count()).toBe(2)
  await remove.click()
  await page.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect.element(first).not.toBeInTheDocument()
  await expect.element(select).toHaveFocus()
  await expect.element(form.getByLabelText('Масса порции, г', { exact: true })).toHaveValue('55,55')
  await expect.element(form.getByLabelText('Комментарий к еде (необязательно)', { exact: true })).toHaveValue('Синтетический новый черновик')
  expect(await db.foodEntries.count()).toBe(1)

  await page.getByRole('button', { name: `Архивировать продукт ${name}`, exact: true }).click()
  await expect.element(form).not.toBeInTheDocument()
  const heading = page.getByRole('heading', { name: 'Запись еды', level: 2, exact: true })
  const remaining = journal.getByRole('listitem').filter({ hasText: 'Синтетическая вторая порция' })
  await remaining.getByRole('button', { name: /^Изменить запись еды/ }).click()
  await expect.element(edit.getByLabelText('Дата записи еды', { exact: true })).toHaveFocus()
  await edit.getByRole('button', { name: 'Отменить правку еды', exact: true }).click()
  await expect.element(heading).toHaveFocus()
  await remaining.getByRole('button', { name: /^Изменить запись еды/ }).click()
  await edit.getByLabelText('Масса порции, г', { exact: true }).fill('225')
  await edit.getByRole('button', { name: 'Сохранить запись еды', exact: true }).click()
  await expect.element(remaining).toHaveTextContent('Завтрак · 225 г · 225 ккал')
  await expect.element(heading).toHaveFocus()
  await remaining.getByRole('button', { name: /^Удалить запись еды/ }).click()
  await page.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect.element(journal).not.toBeInTheDocument()
  await expect.element(heading).toHaveFocus()
  expect(await db.foodEntries.count()).toBe(0)
  expect(await db.products.toArray()).toEqual([expect.objectContaining({ name, archived: true })])
  expect(window.innerWidth).toBe(375)
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth)
  expect((await axe.run(view.container)).violations).toEqual([])
}, 20000)
