import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { db } from '../data/db'
import * as foodRepository from '../data/foodRepository'
import * as productRepository from '../data/productRepository'
import { FoodJournal } from './FoodJournal'
import { ProductCatalog } from './ProductCatalog'
import { DayProvider } from '../ui/DayContext'

const firstProduct = { id: '00000000-0000-4000-8000-000000000071', name: 'Синтетический продукт А', source: '', kcal: 100, protein: null, fat: 0, carbs: null, archived: false }
const secondProduct = { ...firstProduct, id: '00000000-0000-4000-8000-000000000072', name: 'Синтетический продукт Б' }
async function clearDatabase() {
  await db.transaction('rw', db.products, db.foodEntries, async () => { await db.foodEntries.clear(); await db.products.clear() })
}
beforeEach(async () => {
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date('2026-10-14T12:00:00.000Z'))
  await clearDatabase()
  await db.products.bulkAdd([firstProduct, secondProduct])
})
afterEach(async () => { cleanup(); vi.restoreAllMocks(); await clearDatabase(); vi.useRealTimers() })

it('сохранение еды блокирует смену редактора и удаление, а отказ оставляет черновик для повтора', async () => {
  const first = await foodRepository.addFood({ date: '2026-10-14', productId: firstProduct.id, meal: 'breakfast', grams: 100, note: 'Синтетическая порция А' })
  const second = await foodRepository.addFood({ date: '2026-10-14', productId: secondProduct.id, meal: 'breakfast', grams: 200, note: 'Синтетическая порция Б' })
  render(<DayProvider><FoodJournal /></DayProvider>)
  const firstRow = within(await screen.findByRole('list', { name: 'Еда выбранного дня' })).getByText('Синтетическая порция А').closest('li')
  const secondRow = screen.getByText('Синтетическая порция Б').closest('li')
  if (!firstRow || !secondRow) throw new Error('Нужны две сохранённые синтетические порции')
  fireEvent.click(within(firstRow).getByRole('button', { name: /^Изменить запись еды/ }))
  const form = await screen.findByRole('form', { name: 'Редактирование еды' })
  fireEvent.change(within(form).getByLabelText('Масса порции, г'), { target: { value: '125,5' } })
  fireEvent.change(within(form).getByLabelText('Комментарий к еде (необязательно)'), { target: { value: 'Синтетический несохранённый черновик А' } })
  let fail: (reason: unknown) => void = () => { throw new Error('Сохранение не началось') }
  const update = vi.spyOn(foodRepository, 'updateFood').mockImplementationOnce(() => new Promise<void>((_resolve, reject) => { fail = reject }))
  fireEvent.click(within(form).getByRole('button', { name: 'Сохранить запись еды' }))
  await waitFor(() => { expect(update).toHaveBeenCalledTimes(1) })
  expect(within(secondRow).getByRole('button', { name: /^Изменить запись еды/ })).toBeDisabled()
  expect(within(secondRow).getByRole('button', { name: /^Удалить запись еды/ })).toBeDisabled()
  expect(within(form).getByRole('button', { name: 'Отменить правку еды' })).toBeDisabled()
  fail(new DOMException('synthetic-private-food-failure', 'QuotaExceededError'))
  expect(await screen.findByRole('alert')).toHaveTextContent('Не удалось выполнить действие')
  expect(screen.getByRole('alert')).not.toHaveTextContent('synthetic-private-food-failure')
  expect(within(form).getByLabelText('Масса порции, г')).toHaveValue('125,5')
  expect(within(form).getByLabelText('Комментарий к еде (необязательно)')).toHaveValue('Синтетический несохранённый черновик А')
  expect(await db.foodEntries.get(first.id)).toEqual(first)
  expect(await db.foodEntries.get(second.id)).toEqual(second)
  await waitFor(() => { expect(within(form).getByRole('button', { name: 'Сохранить запись еды' })).toBeEnabled() })
  fireEvent.click(within(form).getByRole('button', { name: 'Сохранить запись еды' }))
  await screen.findByText('Запись еды изменена')
  expect(update).toHaveBeenCalledTimes(2)
  expect(await db.foodEntries.get(first.id)).toMatchObject({ grams: 125.5, note: 'Синтетический несохранённый черновик А' })
  expect(await db.foodEntries.get(second.id)).toEqual(second)
  await waitFor(() => { expect(within(secondRow).getByRole('button', { name: /^Изменить запись еды/ })).toBeEnabled() })
  fireEvent.click(within(secondRow).getByRole('button', { name: /^Изменить запись еды/ }))
  expect(await screen.findByRole('form', { name: 'Редактирование еды' })).toHaveTextContent(secondProduct.name)
  expect(screen.getByLabelText('Масса порции, г')).toHaveValue('200')
})

