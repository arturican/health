import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { LabSection } from './LabSection'
import { db } from '../data/db'
import * as repository from '../data/labRepository'
import type { DiaryDocument } from '../domain/document'
import type { LabResult } from '../domain/labResult'

const first: DiaryDocument = { id: '00000000-0000-4000-8000-000000000001', fileId: '00000000-0000-4000-8000-000000000101', date: '2026-10-12', title: 'Первый синтетический бланк', kind: 'lab', note: '' }
const second: DiaryDocument = { ...first, id: '00000000-0000-4000-8000-000000000002', fileId: '00000000-0000-4000-8000-000000000102', date: '2026-10-14', title: 'Второй синтетический бланк' }
const result: LabResult = { id: '00000000-0000-4000-8000-000000000301', documentId: first.id, date: first.date, name: 'Синтетический показатель', value: { type: 'number', number: 0, operator: 'eq' }, unit: '', reference: '', note: '' }

beforeEach(async () => {
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date(2026, 9, 14, 12))
  await db.open()
  await db.labResults.clear()
  await db.documents.clear()
  await db.documents.bulkAdd([first, second])
})
afterEach(async () => {
  cleanup()
  vi.restoreAllMocks()
  await db.labResults.clear()
  await db.documents.clear()
  vi.useRealTimers()
})
async function choose(document = first) {
  const source = await screen.findByLabelText('Бланк для показателей')
  await within(source).findByRole('option', { name: `${document.date} — ${document.title}` })
  fireEvent.change(source, { target: { value: document.id } })
  await screen.findByRole('form', { name: 'Добавление показателя' })
  await screen.findByText('Показателей пока нет.')
}
function fill(name = 'Синтетический показатель', number = '0') {
  fireEvent.change(screen.getByLabelText('Название показателя'), { target: { value: name } })
  fireEvent.change(screen.getByLabelText('Результат числом'), { target: { value: number } })
}
function save() { fireEvent.click(screen.getByRole('button', { name: 'Добавить показатель' })) }

it('просит явно выбрать бланк и показывает варианты по датам без автоматического источника', async () => {
  render(<LabSection />)
  expect(screen.getByRole('heading', { level: 2, name: 'Показатели документа' })).toBeVisible()
  expect(await screen.findByText('Выберите бланк для ввода показателей.')).toBeVisible()
  const source = await screen.findByLabelText('Бланк для показателей')
  expect(source).toHaveValue('')
  expect(screen.queryByRole('form', { name: 'Добавление показателя' })).not.toBeInTheDocument()
  const labels = within(source).getAllByRole('option').map(option => option.textContent)
  expect(labels.slice(-2)).toEqual([`${second.date} — ${second.title}`, `${first.date} — ${first.title}`])
  await db.documents.clear()
  expect(await screen.findByText('Сначала добавьте документ-источник.')).toBeVisible()
  expect(screen.queryByLabelText('Бланк для показателей')).not.toBeInTheDocument()
  expect(screen.queryByRole('form')).not.toBeInTheDocument()
})

it('сохраняет 0, отрицательное число с запятой/знаком и текст с единицами и референсом без интерпретации', async () => {
  render(<LabSection />)
  await choose()
  expect(screen.getByLabelText('Дата показателя')).toHaveValue(first.date)
  fill('Нулевой синтетический показатель')
  save()
  expect(await screen.findByText('Показатель добавлен')).toBeVisible()
  const list = await screen.findByRole('list', { name: 'Показатели выбранного документа' })
  expect(list).toHaveTextContent('Нулевой синтетический показатель')
  expect(list).toHaveTextContent('Единицы: не указаны')
  expect(list).toHaveTextContent('Референс на бланке: не указан')
  expect((await db.labResults.toArray())[0]?.value).toEqual({ type: 'number', number: 0, operator: 'eq' })
  await waitFor(() => { expect(screen.getByLabelText('Название показателя')).toHaveFocus() })
  expect(screen.getByLabelText('Название показателя')).toHaveValue('')
  expect(screen.getByLabelText('Результат числом')).toHaveValue('')
  fireEvent.change(screen.getByLabelText('Дата показателя'), { target: { value: '2026-10-13' } })
  fill('  Отрицательный синтетический показатель  ', '-12,50')
  fireEvent.change(screen.getByLabelText('Знак сравнения'), { target: { value: 'lte' } })
  fireEvent.change(screen.getByLabelText('Единицы (необязательно)'), { target: { value: '  синт. ед.  ' } })
  fireEvent.change(screen.getByLabelText('Референс как на бланке (необязательно)'), { target: { value: '  Буквальный синтетический референс  ' } })
  fireEvent.change(screen.getByLabelText('Заметка к показателю (необязательно)'), { target: { value: '  Синтетическая заметка  ' } })
  save()
  await waitFor(() => { expect(within(list).getAllByRole('listitem')).toHaveLength(2) })
  expect(list).toHaveTextContent('≤ -12,5')
  expect(list).toHaveTextContent('Буквальный синтетический референс')
  expect(list).toHaveTextContent('Синтетическая заметка')
  const negative = (await db.labResults.toArray()).find(row => row.name === 'Отрицательный синтетический показатель')
  expect(negative).toMatchObject({ documentId: first.id, value: { type: 'number', number: -12.5, operator: 'lte' }, unit: 'синт. ед.', reference: 'Буквальный синтетический референс', note: 'Синтетическая заметка' })
  await waitFor(() => { expect(screen.getByLabelText('Название показателя')).toHaveValue('') })
  fireEvent.change(screen.getByLabelText('Формат результата'), { target: { value: 'text' } })
  expect(screen.queryByLabelText('Результат числом')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Знак сравнения')).not.toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Название показателя'), { target: { value: 'Текстовый синтетический показатель' } })
  fireEvent.change(screen.getByLabelText('Результат текстом'), { target: { value: '  Синтетический текст результата  ' } })
  save()
  await waitFor(() => { expect(within(list).getAllByRole('listitem')).toHaveLength(3) })
  expect(list).toHaveTextContent('Синтетический текст результата')
  expect((await db.labResults.toArray()).find(row => row.name === 'Текстовый синтетический показатель')?.value).toEqual({ type: 'text', text: 'Синтетический текст результата' })
  await waitFor(() => { expect(screen.getByLabelText('Формат результата')).toHaveValue('number') })
  expect(screen.getByLabelText('Дата показателя')).toHaveValue(first.date)
})

it('смена источника сбрасывает черновик и показывает только новый список; исчезновение документа убирает старые данные', async () => {
  const other = { ...result, id: '00000000-0000-4000-8000-000000000302', documentId: second.id, date: second.date, name: 'Показатель второго бланка' }
  await db.labResults.bulkAdd([result, other])
  render(<LabSection />)
  const source = await screen.findByLabelText('Бланк для показателей')
  fireEvent.change(source, { target: { value: first.id } })
  expect(await screen.findByText(result.name)).toBeVisible()
  fill('Несохранённый черновик', '5')
  fireEvent.change(source, { target: { value: second.id } })
  expect(await screen.findByText(other.name)).toBeVisible()
  expect(screen.queryByText(result.name)).not.toBeInTheDocument()
  expect(screen.getByLabelText('Название показателя')).toHaveValue('')
  expect(screen.getByLabelText('Дата показателя')).toHaveValue(second.date)
  await db.documents.delete(second.id)
  await waitFor(() => { expect(screen.queryByRole('form', { name: 'Добавление показателя' })).not.toBeInTheDocument() })
  expect(screen.queryByText(other.name)).not.toBeInTheDocument()
  expect(screen.queryByRole('list', { name: 'Показатели выбранного документа' })).not.toBeInTheDocument()
})

it('связывает будущую дату, название и неверные число/текст с первым ошибочным полем', async () => {
  const add = vi.spyOn(repository, 'addLabResult')
  render(<LabSection />)
  await choose()
  fireEvent.change(screen.getByLabelText('Дата показателя'), { target: { value: '2026-10-15' } })
  save()
  expect(screen.getByLabelText('Дата показателя')).toHaveFocus()
  expect(screen.getByLabelText('Дата показателя')).toHaveAccessibleDescription('Дата показателя не может быть в будущем')
  fireEvent.change(screen.getByLabelText('Дата показателя'), { target: { value: first.date } })
  save()
  expect(screen.getByLabelText('Название показателя')).toHaveFocus()
  fill('Синтетический показатель', '1,2,3')
  save()
  expect(screen.getByLabelText('Результат числом')).toHaveFocus()
  expect(screen.getByLabelText('Результат числом')).toHaveAttribute('aria-invalid', 'true')
  fireEvent.change(screen.getByLabelText('Формат результата'), { target: { value: 'text' } })
  save()
  expect(screen.getByLabelText('Результат текстом')).toHaveFocus()
  expect(screen.getByLabelText('Результат текстом')).toHaveAttribute('aria-invalid', 'true')
  expect(add).not.toHaveBeenCalled()
  expect(await db.labResults.count()).toBe(0)
})

it('сохраняет полный черновик при отказе DB, скрывает детали и допускает повторную попытку', async () => {
  const add = vi.spyOn(repository, 'addLabResult').mockRejectedValueOnce(Object.assign(new Error('Синтетические закрытые детали'), { name: 'QuotaExceededError' }))
  render(<LabSection />)
  await choose()
  fill('Синтетический показатель', '-1,25')
  fireEvent.change(screen.getByLabelText('Знак сравнения'), { target: { value: 'lt' } })
  fireEvent.change(screen.getByLabelText('Референс как на бланке (необязательно)'), { target: { value: 'Буквальный референс' } })
  save()
  expect(await screen.findByRole('alert')).toHaveTextContent('Не удалось выполнить действие')
  expect(screen.queryByText('Синтетические закрытые детали')).not.toBeInTheDocument()
  expect(screen.getByLabelText('Название показателя')).toHaveValue('Синтетический показатель')
  expect(screen.getByLabelText('Результат числом')).toHaveValue('-1,25')
  expect(screen.getByLabelText('Знак сравнения')).toHaveValue('lt')
  expect(screen.getByLabelText('Референс как на бланке (необязательно)')).toHaveValue('Буквальный референс')
  save()
  expect(await screen.findByText('Показатель добавлен')).toBeVisible()
  expect(add).toHaveBeenCalledTimes(2)
  expect((await db.labResults.toArray())[0]?.value).toEqual({ type: 'number', number: -1.25, operator: 'lt' })
})

it('блокирует источник, поля и повторный клик до завершения сохранения', async () => {
  let complete: ((value: LabResult) => void) | undefined
  const pending = new Promise<LabResult>(resolve => { complete = resolve })
  const add = vi.spyOn(repository, 'addLabResult').mockReturnValueOnce(pending)
  render(<LabSection />)
  await choose()
  fill()
  save()
  const button = await screen.findByRole('button', { name: 'Сохраняем…' })
  expect(button).toBeDisabled()
  expect(screen.getByLabelText('Бланк для показателей')).toBeDisabled()
  expect(screen.getByLabelText('Название показателя')).toBeDisabled()
  fireEvent.click(button)
  expect(add).toHaveBeenCalledTimes(1)
  complete?.(result)
  expect(await screen.findByText('Показатель добавлен')).toBeVisible()
  await waitFor(() => { expect(screen.getByLabelText('Название показателя')).toHaveFocus() })
})

it('внешняя блокировка сохраняет черновик и восстанавливает доступные действия после снятия', async () => {
  const view = render(<LabSection />)
  await choose()
  fill('Сохранённый черновик', '5,5')
  view.rerender(<LabSection blocked />)
  expect(screen.getByLabelText('Бланк для показателей')).toBeDisabled()
  expect(screen.getByLabelText('Название показателя')).toBeDisabled()
  expect(screen.getByRole('button', { name: 'Добавить показатель' })).toBeDisabled()
  view.rerender(<LabSection blocked={false} />)
  expect(screen.getByLabelText('Название показателя')).toBeEnabled()
  expect(screen.getByLabelText('Название показателя')).toHaveValue('Сохранённый черновик')
  expect(screen.getByLabelText('Результат числом')).toHaveValue('5,5')
})
