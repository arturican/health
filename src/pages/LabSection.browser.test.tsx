import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { page, userEvent } from 'vitest/browser'
import { cleanup, render } from 'vitest-browser-react'
import axe from 'axe-core'
import { App } from '../App'
import { db } from '../data/db'
import { addDocument } from '../data/documentRepository'
import { addLabResult, listLabResults } from '../data/labRepository'
import '../styles.css'

async function resetTestState() {
  await cleanup()
  expect(import.meta.env.MODE).toBe('test')
  expect(db.name).toBe('health-diary-tests')
  const tables = [db.metadata, db.profiles, db.weights, db.products, db.foodEntries, db.nutritionDays, db.steps, db.workouts, db.energyPlans, db.files, db.photos, db.documents, db.labResults]
  await db.transaction('rw', tables, async () => { for (const table of tables) await table.clear() })
  window.history.replaceState(null, '', window.location.pathname)
}
beforeEach(async () => {
  await resetTestState()
  await page.viewport(375, 812)
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date('2026-10-14T12:00:00.000Z'))
})
afterEach(async () => {
  await resetTestState()
  vi.restoreAllMocks()
  vi.useRealTimers()
  await page.viewport(1280, 800)
})

test('показатели сохраняют число, знак и текст у выбранного бланка, смена источника сбрасывает черновик', async () => {
  const pdf = new File(['%PDF-1.7\nsynthetic-laboratory-ui\n%%EOF\n'], 'synthetic-lab.pdf', { type: 'application/pdf' })
  const first = await addDocument({ date: '2026-10-14', title: 'Синтетический бланк с длинным названием для мобильного списка', kind: 'lab', note: '' }, pdf)
  const second = await addDocument({ date: '2026-10-13', title: 'Другой синтетический бланк', kind: 'lab', note: '' }, pdf)
  let view = await render(<App />)
  await page.getByRole('link', { name: 'Документы', exact: true }).click()
  const source = page.getByLabelText('Бланк для показателей', { exact: true })
  await expect.element(source.getByRole('option', { name: `2026-10-14 — ${first.title}`, exact: true })).toBeInTheDocument()
  await source.selectOptions(first.id)
  const date = page.getByLabelText('Дата показателя', { exact: true })
  const name = page.getByLabelText('Название показателя', { exact: true })
  const type = page.getByLabelText('Формат результата', { exact: true })
  const operator = page.getByLabelText('Знак сравнения', { exact: true })
  const number = page.getByLabelText('Результат числом', { exact: true })
  const text = page.getByLabelText('Результат текстом', { exact: true })
  const unit = page.getByLabelText('Единицы (необязательно)', { exact: true })
  const reference = page.getByLabelText('Референс как на бланке (необязательно)', { exact: true })
  const note = page.getByLabelText('Заметка к показателю (необязательно)', { exact: true })
  const save = page.getByRole('button', { name: 'Добавить показатель', exact: true })
  const list = page.getByRole('list', { name: 'Показатели выбранного документа', exact: true })
  const notice = page.getByRole('status').filter({ hasText: 'Показатель добавлен' })
  await date.fill('2026-10-15')
  await name.fill('Синтетический нулевой результат')
  await number.fill('0')
  await save.click()
  await expect.element(date).toHaveFocus()
  await expect.element(date).toHaveAttribute('aria-invalid', 'true')
  expect(await db.labResults.count()).toBe(0)
  await date.fill('2026-10-14')
  await number.fill('не число')
  await save.click()
  await expect.element(number).toHaveFocus()
  await expect.element(number).toHaveAttribute('aria-invalid', 'true')
  await expect.element(name).toHaveValue('Синтетический нулевой результат')
  expect(await db.labResults.count()).toBe(0)
  await number.fill('0')
  await unit.fill('условные единицы')
  const zeroReference = '≤ 0,0000002; точный текст синтетического бланка'
  await reference.fill(zeroReference)
  await note.fill('Без интерпретации референса')
  await userEvent.keyboard('{Tab}')
  await expect.element(save).toHaveFocus()
  let locked = false
  let release = false
  const lock = db.transaction('rw', db.documents, db.labResults, async () => {
    locked = true
    while (!release) await db.labResults.count()
  })
  await expect.poll(() => locked).toBe(true)
  try {
    await userEvent.keyboard('{Enter}')
    await expect.element(number).toBeDisabled()
    await expect.element(source).toBeDisabled()
    await expect.element(page.getByRole('button', { name: `Удалить документ 1: ${first.title}`, exact: true })).toBeDisabled()
  } finally { release = true; await lock }
  await expect.element(notice).toHaveTextContent('Показатель добавлен')
  await expect.element(name).toHaveFocus()
  await expect.element(name).toHaveValue('')
  await expect.element(list).toHaveTextContent(zeroReference)
  await expect.element(list.getByText('Результат: 0', { exact: true })).toBeVisible()
  await date.fill('2026-10-13')
  await name.fill('Синтетический отрицательный результат')
  await operator.selectOptions('lte')
  await number.fill('-0,0000001')
  await unit.fill('мг/л')
  await reference.fill('Как на бланке: от −1 до +1; без оценки')
  await save.click()
  await expect.element(list).toHaveTextContent('≤ -0,0000001')
  await type.selectOptions('text')
  await expect.element(number).not.toBeInTheDocument()
  await expect.element(operator).not.toBeInTheDocument()
  await name.fill('Синтетический текстовый результат')
  await text.fill('Не обнаружено (синтетический образец)')
  await save.click()
  await expect.element(list).toHaveTextContent('Не обнаружено (синтетический образец)')
  await expect.element(list.getByText('Единицы: не указаны', { exact: true })).toBeVisible()
  await expect.element(list.getByText('Референс на бланке: не указан', { exact: true })).toBeVisible()
  const saved = await listLabResults(first.id)
  expect(saved).toHaveLength(3)
  expect(Array.from(list.element().querySelectorAll('article time')).map(time => time.getAttribute('datetime'))).toEqual(saved.map(result => result.date))
  expect(saved.find(result => result.name === 'Синтетический нулевой результат')).toMatchObject({ documentId: first.id, date: '2026-10-14', value: { type: 'number', number: 0, operator: 'eq' }, unit: 'условные единицы', reference: zeroReference, note: 'Без интерпретации референса' })
  expect(saved.find(result => result.name === 'Синтетический отрицательный результат')).toMatchObject({ date: '2026-10-13', value: { type: 'number', number: -0.0000001, operator: 'lte' }, unit: 'мг/л', reference: 'Как на бланке: от −1 до +1; без оценки' })
  expect(saved.find(result => result.name === 'Синтетический текстовый результат')).toMatchObject({ value: { type: 'text', text: 'Не обнаружено (синтетический образец)' }, unit: '', reference: '', note: '' })
  await name.fill('Несохранённый синтетический черновик')
  await source.selectOptions(second.id)
  await expect.element(name).toHaveValue('')
  await expect.element(type).toHaveValue('number')
  await expect.element(date).toHaveValue(second.date)
  await expect.element(number).toHaveValue('')
  await expect.element(list).not.toBeInTheDocument()
  await name.fill('Показатель другого бланка')
  await operator.selectOptions('gt')
  await number.fill('1,23456789')
  await save.click()
  await expect.element(list).toHaveTextContent('> 1,23456789')
  const otherSaved = await listLabResults(second.id)
  expect(otherSaved).toHaveLength(1)
  expect(otherSaved[0]).toMatchObject({ documentId: second.id, value: { type: 'number', number: 1.23456789, operator: 'gt' } })
  await source.selectOptions(first.id)
  await expect.element(list).toHaveTextContent('Синтетический нулевой результат')
  await expect.element(list).not.toHaveTextContent('Показатель другого бланка')
  expect(await listLabResults(first.id)).toEqual(saved)
  expect((await axe.run(view.container)).violations).toEqual([])
  await view.unmount()
  view = await render(<App />)
  await source.selectOptions(first.id)
  await expect.element(list).toHaveTextContent('≤ -0,0000001')
  await expect.element(list).toHaveTextContent('Не обнаружено (синтетический образец)')
  expect(await listLabResults(first.id)).toEqual(saved)
  expect(await listLabResults(second.id)).toEqual(otherSaved)
  for (const result of await db.labResults.toArray()) expect(await db.documents.get(result.documentId)).toBeDefined()
  const original = await db.files.get(first.fileId)
  if (!original) throw new Error('Исходный синтетический файл должен сохраниться')
  expect(new Uint8Array(await original.blob.arrayBuffer())).toEqual(new Uint8Array(await pdf.arrayBuffer()))
  expect(await db.files.count()).toBe(2)
  expect(window.innerWidth).toBe(375)
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth)
  expect((await axe.run(view.container)).violations).toEqual([])
  const externalRequests = performance.getEntriesByType('resource').map(entry => new URL(entry.name)).filter(url =>
    ['http:', 'https:'].includes(url.protocol) && url.origin !== window.location.origin,
  )
  expect(externalRequests).toEqual([])
}, 15000)

test('правка и удаление отдельного показателя сохраняют точность, источник и соседние записи', async () => {
  const pdf = new File(['%PDF-1.7\nsynthetic-laboratory-edit\n%%EOF\n'], 'synthetic-lab-edit.pdf', { type: 'application/pdf' })
  const sourceRecord = await addDocument({ date: '2026-10-14', title: 'Синтетический источник правки', kind: 'lab', note: '' }, pdf)
  const otherSource = await addDocument({ date: '2026-10-13', title: 'Другой синтетический источник', kind: 'lab', note: '' }, pdf)
  const fields = { documentId: sourceRecord.id, date: '2026-10-14', name: 'Синтетический очень малый результат', value: { type: 'number', number: 0.0000001, operator: 'eq' }, unit: 'условные единицы', reference: 'Исходный референс без интерпретации', note: 'Исходная синтетическая заметка' }
  const original = await addLabResult(fields)
  const neighbour = await addLabResult({ ...fields, date: '2026-10-13', name: 'Соседний синтетический показатель', value: { type: 'text', text: 'Сохранить соседний текст' } })
  const otherResult = await addLabResult({ ...fields, documentId: otherSource.id, name: 'Показатель другого источника' })
  async function expectOriginalFile() {
    const file = await db.files.get(sourceRecord.fileId)
    if (!file) throw new Error('Исходный синтетический файл должен остаться')
    expect(new Uint8Array(await file.blob.arrayBuffer())).toEqual(new Uint8Array(await pdf.arrayBuffer()))
    expect(await db.documents.get(sourceRecord.id)).toEqual(sourceRecord)
    expect(await db.documents.get(otherSource.id)).toEqual(otherSource)
    expect(await db.files.count()).toBe(2)
  }
  let view = await render(<App />)
  await page.getByRole('link', { name: 'Документы', exact: true }).click()
  const source = page.getByLabelText('Бланк для показателей', { exact: true })
  await source.selectOptions(sourceRecord.id)
  const list = page.getByRole('list', { name: 'Показатели выбранного документа', exact: true })
  const editor = page.getByRole('form', { name: 'Редактирование показателя', exact: true })
  const addForm = page.getByRole('form', { name: 'Добавление показателя', exact: true })
  const date = editor.getByLabelText('Дата показателя', { exact: true })
  const name = editor.getByLabelText('Название показателя', { exact: true })
  const type = editor.getByLabelText('Формат результата', { exact: true })
  const number = editor.getByLabelText('Результат числом', { exact: true })
  const text = editor.getByLabelText('Результат текстом', { exact: true })
  const operator = editor.getByLabelText('Знак сравнения', { exact: true })
  const unit = editor.getByLabelText('Единицы (необязательно)', { exact: true })
  const reference = editor.getByLabelText('Референс как на бланке (необязательно)', { exact: true })
  const note = editor.getByLabelText('Заметка к показателю (необязательно)', { exact: true })
  const save = editor.getByRole('button', { name: 'Сохранить показатель', exact: true })
  await list.getByRole('button', { name: `Изменить показатель 1: ${original.name}`, exact: true }).click()
  await expect.element(number).toHaveValue('0.0000001')
  await expect.element(date).toHaveValue(original.date)
  await expect.element(name).toHaveValue(original.name)
  await expect.element(operator).toHaveValue('eq')
  await expect.element(unit).toHaveValue(original.unit)
  await expect.element(reference).toHaveValue(original.reference)
  await expect.element(note).toHaveValue(original.note)
  await expect.element(source).toBeDisabled()
  await expect.element(page.getByRole('button', { name: `Изменить документ 1: ${sourceRecord.title}`, exact: true })).toBeDisabled()
  await name.fill('Отменённая синтетическая правка')
  await number.fill('999')
  await editor.getByRole('button', { name: 'Отменить правку показателя', exact: true }).click()
  await expect.element(editor).not.toBeInTheDocument()
  await expect.element(addForm.getByLabelText('Название показателя', { exact: true })).toHaveFocus()
  expect(await db.labResults.get(original.id)).toEqual(original)
  await list.getByRole('button', { name: `Изменить показатель 1: ${original.name}`, exact: true }).click()
  await expect.element(number).toHaveValue('0.0000001')
  await note.click()
  await userEvent.keyboard('{Tab}')
  await expect.element(save).toHaveFocus()
  await userEvent.keyboard('{Enter}')
  await expect.element(page.getByRole('status').filter({ hasText: 'Показатель обновлён' })).toHaveTextContent('Показатель обновлён')
  await expect.element(addForm.getByLabelText('Название показателя', { exact: true })).toHaveFocus()
  expect(await db.labResults.get(original.id)).toEqual(original)
  await list.getByRole('button', { name: `Изменить показатель 1: ${original.name}`, exact: true }).click()
  await date.fill('2026-10-15')
  await save.click()
  await expect.element(date).toHaveFocus()
  await expect.element(date).toHaveAttribute('aria-invalid', 'true')
  expect(await db.labResults.get(original.id)).toEqual(original)
  const edited = { ...original, date: '2026-10-12', name: 'Обновлённый синтетический показатель с длинным названием', value: { type: 'text', text: 'Синтетический текст после правки' }, unit: 'новые единицы', reference: '≤ 0,0000002; текст как на бланке', note: 'Новая синтетическая заметка' }
  await date.fill(edited.date)
  await name.fill(edited.name)
  await type.selectOptions('text')
  await text.fill(edited.value.text)
  await unit.fill(edited.unit)
  await reference.fill(edited.reference)
  await note.fill(edited.note)
  await userEvent.keyboard('{Tab}{Enter}')
  await expect.element(list).toHaveTextContent(edited.value.text)
  expect(await db.labResults.get(original.id)).toEqual(edited)
  expect(Array.from(list.element().querySelectorAll('article time')).map(time => time.getAttribute('datetime'))).toEqual(['2026-10-13', '2026-10-12'])
  await list.getByRole('button', { name: `Изменить показатель 2: ${edited.name}`, exact: true }).click()
  await expect.element(text).toHaveValue(edited.value.text)
  await type.selectOptions('number')
  await number.fill('-0,0000002')
  await operator.selectOptions('gte')
  await save.click()
  await expect.element(list).toHaveTextContent('≥ -0,0000002')
  const finalRecord = { ...edited, value: { type: 'number', number: -0.0000002, operator: 'gte' } }
  expect(await db.labResults.get(original.id)).toEqual(finalRecord)
  expect(await db.labResults.get(neighbour.id)).toEqual(neighbour)
  expect(await db.labResults.get(otherResult.id)).toEqual(otherResult)
  await expectOriginalFile()
  const remove = list.getByRole('button', { name: `Удалить показатель 2: ${edited.name}`, exact: true })
  await remove.click()
  const confirmation = page.getByRole('alertdialog')
  await expect.element(confirmation).toHaveTextContent(`Удалить показатель «${edited.name}» за ${edited.date}?`)
  await expect.element(confirmation.getByRole('button', { name: 'Отмена', exact: true })).toHaveFocus()
  await expect.element(source).toBeDisabled()
  await expect.element(addForm.getByLabelText('Название показателя', { exact: true })).toBeDisabled()
  await expect.element(page.getByRole('button', { name: `Удалить документ 1: ${sourceRecord.title}`, exact: true })).toBeDisabled()
  expect((await axe.run(view.container)).violations).toEqual([])
  await userEvent.keyboard('{Enter}')
  await expect.element(confirmation).not.toBeInTheDocument()
  await expect.element(remove).toHaveFocus()
  expect(await db.labResults.get(original.id)).toEqual(finalRecord)
  await remove.click()
  await confirmation.getByRole('button', { name: 'Подтвердить удаление', exact: true }).click()
  await expect.element(page.getByRole('status').filter({ hasText: 'Показатель удалён' })).toHaveTextContent('Показатель удалён')
  await expect.element(page.getByRole('heading', { level: 3, name: 'Записанные показатели', exact: true })).toHaveFocus()
  expect(await db.labResults.get(original.id)).toBeUndefined()
  expect(await listLabResults(sourceRecord.id)).toEqual([neighbour])
  expect(await listLabResults(otherSource.id)).toEqual([otherResult])
  await expectOriginalFile()
  await view.unmount()
  view = await render(<App />)
  await source.selectOptions(sourceRecord.id)
  await expect.element(list).toHaveTextContent(neighbour.name)
  await expect.element(list).not.toHaveTextContent(edited.name)
  expect(await listLabResults(sourceRecord.id)).toEqual([neighbour])
  expect(await listLabResults(otherSource.id)).toEqual([otherResult])
  await expectOriginalFile()
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth)
  expect((await axe.run(view.container)).violations).toEqual([])
  const externalRequests = performance.getEntriesByType('resource').map(entry => new URL(entry.name)).filter(url =>
    ['http:', 'https:'].includes(url.protocol) && url.origin !== window.location.origin,
  )
  expect(externalRequests).toEqual([])
}, 15000)
